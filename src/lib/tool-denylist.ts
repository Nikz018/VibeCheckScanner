export function toolBrandPattern(): RegExp {
  const body = TOOL_BRANDS.map((name) => name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/\s+/g, "\\s+")).join("|");
  return new RegExp(`(?:${body})`, "gi");
}
